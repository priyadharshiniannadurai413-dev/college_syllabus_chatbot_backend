from fpdf import FPDF

OUT_FILE = "backend_documentation.pdf"

ACCENT = (13, 71, 161)      # deep blue
LIGHT = (227, 236, 250)     # light blue row fill
CODE_BG = (245, 245, 245)
GREY = (90, 90, 90)


def s(text: str) -> str:
    """Sanitize text to latin-1 so fpdf2 core fonts never raise."""
    replacements = {
        "\u2192": "->", "\u2190": "<-", "\u2713": "[OK]", "\u2717": "[X]",
        "\u2014": "--", "\u2013": "-", "\u2018": "'", "\u2019": "'",
        "\u201c": '"', "\u201d": '"', "\u2026": "...", "\u00d7": "x",
        "\u2265": ">=", "\u2264": "<=", "\u2022": "-",
    }
    for k, v in replacements.items():
        text = text.replace(k, v)
    return text.encode("latin-1", "replace").decode("latin-1")


class Doc(FPDF):
    def header(self):
        if self.page_no() == 1:
            return
        self.set_y(10)
        self.set_x(self.l_margin)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(*GREY)
        half = (self.w - self.l_margin - self.r_margin) / 2
        self.cell(half, 6, s("Backend Documentation - Syllabus Chatbot"), align="L")
        self.cell(half, 6, f"Page {self.page_no()}", align="R")
        self.ln(10)

    def footer(self):
        self.set_y(-14)
        self.set_draw_color(200, 200, 200)
        self.line(15, self.get_y(), self.w - 15, self.get_y())
        self.set_font("Helvetica", "I", 7.5)
        self.set_text_color(*GREY)
        self.cell(0, 8, s("Generated by generate_docs_pdf.py - backend_langchain project"), align="C")

    # ── building blocks ──────────────────────────────────────────────────
    def h1(self, num, title):
        if self.get_y() > 240:
            self.add_page()
        self.ln(4)
        self.set_fill_color(*ACCENT)
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 14)
        self.cell(0, 10, s(f"  {num}. {title}"), fill=True, new_x="LMARGIN", new_y="NEXT")
        self.ln(4)

    def h2(self, title):
        if self.get_y() > 255:
            self.add_page()
        self.set_text_color(*ACCENT)
        self.set_font("Helvetica", "B", 11.5)
        self.cell(0, 7, s(title), new_x="LMARGIN", new_y="NEXT")
        self.ln(1)

    def para(self, text, size=10):
        self.set_text_color(30, 30, 30)
        self.set_font("Helvetica", "", size)
        self.multi_cell(0, 5.2, s(text))
        self.ln(1.5)

    def bullets(self, items):
        for it in items:
            if self.get_y() > 270:
                self.add_page()
            self.set_x(self.l_margin)
            self.set_text_color(*ACCENT)
            self.set_font("Helvetica", "B", 10)
            self.cell(6, 5.2, "-", align="C")
            self.set_text_color(30, 30, 30)
            self.set_font("Helvetica", "", 10)
            self.multi_cell(0, 5.2, s(it))
        self.ln(1.5)

    def code(self, lines):
        self.set_fill_color(*CODE_BG)
        self.set_draw_color(210, 210, 210)
        self.set_font("Courier", "", 9)
        self.set_text_color(40, 40, 40)
        lh = 4.6
        block_h = len(lines) * lh + 4
        if self.get_y() + block_h > 275:
            self.add_page()
        x, y = self.get_x(), self.get_y()
        self.rect(x, y, self.w - x - 15, block_h, "DF")
        self.set_xy(x + 2, y + 2)
        for line in lines:
            self.cell(self.w - x - 19, lh, s(line), new_x="LMARGIN", new_y="NEXT")
            self.set_x(x + 2)
        self.set_xy(x, y + block_h + 3)

    def table(self, headers, rows, widths):
        if self.get_y() > 230:
            self.add_page()
        self.set_font("Helvetica", "B", 9)
        self.set_fill_color(*ACCENT)
        self.set_text_color(255, 255, 255)
        for h, w in zip(headers, widths):
            self.cell(w, 7, s(h), border=1, fill=True, align="C")
        self.ln()
        self.set_font("Helvetica", "", 8.7)
        fill = False
        for row in rows:
            heights = []
            for cell, w in zip(row, widths):
                n_lines = max(1, int(len(s(cell)) / (w / 1.75)) + 1)
                heights.append(n_lines * 4.8 + 2)
            rh = max(heights)
            if self.get_y() + rh > 278:
                self.add_page()
                self.set_font("Helvetica", "B", 9)
                self.set_fill_color(*ACCENT)
                self.set_text_color(255, 255, 255)
                for h, w in zip(headers, widths):
                    self.cell(w, 7, s(h), border=1, fill=True, align="C")
                self.ln()
                self.set_font("Helvetica", "", 8.7)
            y0 = self.get_y()
            x0 = self.get_x()
            fill = not fill
            self.set_fill_color(*(LIGHT if fill else (255, 255, 255)))
            self.set_text_color(30, 30, 30)
            for cell, w in zip(row, widths):
                x = self.get_x()
                self.rect(x, y0, w, rh, "D")
                self.set_xy(x + 1, y0 + 1)
                self.multi_cell(w - 2, 4.8, s(cell))
                self.set_xy(x + w, y0)
            self.set_xy(x0, y0 + rh)
        self.ln(3)


