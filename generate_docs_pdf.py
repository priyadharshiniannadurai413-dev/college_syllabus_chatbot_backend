            ["calculate_cgpa", "CGPA/GPA arithmetic from semester GPAs", "cgpa"],
            ["syllabus_rag_search", "Vector search over embedded course PDFs in MongoDB", "syllabus, ambiguous"],
            ["web_search_tool", "Tavily API live web search", "web_search, ambiguous"],
