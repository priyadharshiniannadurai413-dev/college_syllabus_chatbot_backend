        "    |   |-- __init__.py     Tool registry: merges local + GitHub tools",
        "    |   |-- cgpa_tool.py    calculate_cgpa (local math)",
        "    |   |-- rag_tool.py     syllabus_rag_search (searches course PDFs)",
        "    |   `-- tavily_tool.py  web_search_tool (live web search)",
